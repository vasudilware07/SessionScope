import { jsx as _jsx } from "react/jsx-runtime";
import React from 'react';
import { createRoot } from 'react-dom/client';
import { BrowserRouter } from 'react-router-dom';
import App from './App';
import './style.css';
import { createTracker } from '@sessionscope/tracking-sdk';
const tracker = window.self !== window.top ? { track: () => { }, flush: async () => { } } : createTracker({ projectId: import.meta.env.VITE_PROJECT_ID ?? 'demo-project', endpoint: `${import.meta.env.VITE_API_URL ?? 'http://localhost:4000'}/api/v1/events`, onAccepted: n => window.dispatchEvent(new CustomEvent('ss-accepted', { detail: n })), onError: () => window.dispatchEvent(new Event('ss-error')) });
window.sessionScopeTracker = tracker;
createRoot(document.getElementById('root')).render(_jsx(React.StrictMode, { children: _jsx(BrowserRouter, { children: _jsx(App, { tracker: tracker }) }) }));
